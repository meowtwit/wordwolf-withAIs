export function pickTopic(rng = Math.random) {
  const pair = TOPIC_PAIRS[Math.floor(rng() * TOPIC_PAIRS.length)];
  // どちらを多数派にするかもランダム
  return rng() < 0.5
    ? { majority: pair.a, minority: pair.b }
    : { majority: pair.b, minority: pair.a };
}

export function hintsFor(word) {
  for (const pair of TOPIC_PAIRS) {
    if (pair.a.word === word) return pair.a.hints;
    if (pair.b.word === word) return pair.b.hints;
  }
  return [];
}

export function allWords() {
  return TOPIC_PAIRS.flatMap((p) => [p.a, p.b]);
}
